CREATE TABLE alerts (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        external_id VARCHAR(255) UNIQUE,
                        title VARCHAR(200) NOT NULL,
                        description TEXT NOT NULL,
                        action_guidance TEXT,
                        category VARCHAR(50) NOT NULL,
                        risk_level VARCHAR(20) NOT NULL,
                        city VARCHAR(100),
                        location_uf VARCHAR(2) NOT NULL,
                        ibge_code VARCHAR(7),
                        source_name VARCHAR(100) NOT NULL,
                        source_url TEXT,
                        published_at TIMESTAMP NOT NULL,
                        created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_alert_city_uf ON alerts(city, location_uf);
CREATE INDEX idx_alert_ibge ON alerts(ibge_code);
CREATE INDEX idx_alert_published_at ON alerts(published_at);