CREATE TABLE subscriptions (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               user_id BIGINT NOT NULL,
                               location_name VARCHAR(100),
                               cep VARCHAR(9),
                               category_filter VARCHAR(50),
                               city_filter VARCHAR(100),
                               region_filter VARCHAR(2),
                               ibge_code VARCHAR(7),
                               latitude DOUBLE PRECISION,
                               longitude DOUBLE PRECISION,
                               current_risk_level VARCHAR(20) NOT NULL,
                               created_at TIMESTAMP NOT NULL,

                               CONSTRAINT fk_subscriptions_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES users(id)
);

CREATE INDEX idx_subscriptions_user_id ON subscriptions(user_id);
CREATE INDEX idx_subscriptions_ibge ON subscriptions(ibge_code);
CREATE INDEX idx_subscriptions_city_region ON subscriptions(city_filter, region_filter);